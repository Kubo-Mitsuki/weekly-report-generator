import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseDate, weekDates } from '../slide.js';

// 今週 = 基準日〜6日後（基準日が先頭）、先週 = 基準日の7日前〜前日
const cases = [
  {
    base: '2026/10/20',
    last: ['10/13', '10/14', '10/15', '10/16', '10/17', '10/18', '10/19'],
    this: ['10/20', '10/21', '10/22', '10/23', '10/24', '10/25', '10/26'],
  },
  {
    base: '2026/10/27', // 月またぎ
    last: ['10/20', '10/21', '10/22', '10/23', '10/24', '10/25', '10/26'],
    this: ['10/27', '10/28', '10/29', '10/30', '10/31', '11/01', '11/02'],
  },
  {
    base: '2026/12/29', // 年またぎ
    last: ['12/22', '12/23', '12/24', '12/25', '12/26', '12/27', '12/28'],
    this: ['12/29', '12/30', '12/31', '01/01', '01/02', '01/03', '01/04'],
  },
  {
    base: '2026-10-20', // ハイフン区切りも受け付ける
    last: ['10/13', '10/14', '10/15', '10/16', '10/17', '10/18', '10/19'],
    this: ['10/20', '10/21', '10/22', '10/23', '10/24', '10/25', '10/26'],
  },
];

for (const c of cases) {
  test(`weekDates: ${c.base}`, () => {
    const base = parseDate(c.base);
    assert.deepEqual(weekDates(base, true), c.last);
    assert.deepEqual(weekDates(base, false), c.this);
  });
}
